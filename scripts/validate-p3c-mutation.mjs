#!/usr/bin/env node
// P3-C mutation check for the frozen Policy A content-uniqueness rule.
//
// Each mutation is a controlled edit to the *text* of the production resolver.
// Every mutant is loaded as its own module instance and executed against the
// exact same frozen Policy A case module the production validator uses, so a
// mutant is killed only when it changes observable Policy A behavior.
//
// A mutant that still passes every case is a SURVIVOR. Non-equivalent survivors
// are a freeze failure. Equivalent mutants are permitted but must be proven:
// this harness therefore also runs behaviour-preserving CONTROL mutants, which
// are required to survive. If the controls do not survive, the harness itself is
// not discriminating and every "killed" result from this run is void.
//
// Synthetic temporary fixtures only. No R4 evidence is read and no R4 outcome
// is generated by this script.
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { policyACases } from './market-outcomes/policy-a-cases.mjs';

const PRIMARY = 'scripts/market-outcomes/index.mjs';

// The exact frozen Policy A lines under test.
const PRE_TARGET = "      if (futurePrice.some(p => p.providerObservedAt < targetAt)) reason = 'PRE_TARGET_PRICE_EVIDENCE';";
const REUSE_TEST = "p.provider === q.provider && (p.normalizedPayloadDigest === q.normalizedPayloadDigest || p.rawResponseDigest === q.rawResponseDigest)";
const REUSE_BRANCH = `${REUSE_TEST}))) reason = 'REUSED_REFERENCE_PRICE_EVIDENCE';`;
const ACCEPT = "    if (!reason) { future = candidate; break; }";
const COUNT = "    rejected[reason] = (rejected[reason] ?? 0) + 1;";

const MUTATIONS = [
  { id: 'M1', critical: true, name: 'remove raw-digest comparison', find: REUSE_TEST, replace: "p.provider === q.provider && (p.normalizedPayloadDigest === q.normalizedPayloadDigest)" },
  { id: 'M2', critical: true, name: 'remove normalized-digest comparison', find: REUSE_TEST, replace: "p.provider === q.provider && (p.rawResponseDigest === q.rawResponseDigest)" },
  { id: 'M3', critical: true, name: 'require both digests instead of either', find: REUSE_TEST, replace: "p.provider === q.provider && (p.normalizedPayloadDigest === q.normalizedPayloadDigest && p.rawResponseDigest === q.rawResponseDigest)" },
  { id: 'M4', critical: true, name: 'remove provider equality condition', find: REUSE_TEST, replace: "(p.normalizedPayloadDigest === q.normalizedPayloadDigest || p.rawResponseDigest === q.rawResponseDigest)" },
  { id: 'M5', critical: true, name: 'invert provider equality condition', find: REUSE_TEST, replace: "p.provider !== q.provider && (p.normalizedPayloadDigest === q.normalizedPayloadDigest || p.rawResponseDigest === q.rawResponseDigest)" },
  { id: 'M6', critical: true, name: 'move REUSED ahead of PRE_TARGET', find: `${PRE_TARGET}\n      else if (futurePrice.some(p => referencePrice.some(q => ${REUSE_TEST}))) reason = 'REUSED_REFERENCE_PRICE_EVIDENCE';`, replace: `if (futurePrice.some(p => referencePrice.some(q => ${REUSE_TEST}))) reason = 'REUSED_REFERENCE_PRICE_EVIDENCE';\n      else if (futurePrice.some(p => p.providerObservedAt < targetAt)) reason = 'PRE_TARGET_PRICE_EVIDENCE';` },
  { id: 'M7', critical: true, name: 'accept reused first candidate instead of continuing', find: ACCEPT, replace: "    if (!reason || reason === 'REUSED_REFERENCE_PRICE_EVIDENCE') { future = candidate; break; }" },
  { id: 'M8', critical: true, name: 'stop counting REUSED in rejectedCandidatesByReason', find: COUNT, replace: "    if (reason !== 'REUSED_REFERENCE_PRICE_EVIDENCE') rejected[reason] = (rejected[reason] ?? 0) + 1;" },
  // Controls: proven-equivalent edits that must survive. They demonstrate the
  // harness discriminates on behavior rather than on textual difference.
  { id: 'C1', critical: false, equivalent: true, name: 'CONTROL equivalent: reformat the reuse predicate across lines', find: REUSE_BRANCH, replace: `p.provider === q.provider && (\n        p.normalizedPayloadDigest === q.normalizedPayloadDigest || p.rawResponseDigest === q.rawResponseDigest)))) reason = 'REUSED_REFERENCE_PRICE_EVIDENCE';` },
  { id: 'C2', critical: false, equivalent: true, name: 'CONTROL equivalent: add an explanatory comment', find: PRE_TARGET, replace: `// frozen P3-C Policy A: pre-target evidence takes precedence over content reuse.\n${PRE_TARGET}` },
];

function applyMutation(text, mutation) {
  const occurrences = text.split(mutation.find).length - 1;
  if (occurrences !== 1) throw new Error(`MUTATION_ANCHOR_NOT_UNIQUE:${mutation.id}:${occurrences}`);
  const mutated = text.replace(mutation.find, mutation.replace);
  if (mutated === text) throw new Error(`MUTATION_NO_CHANGE:${mutation.id}`);
  return mutated;
}

async function runCases(label, modulePath) {
  let api;
  try { api = await import(pathToFileURL(modulePath).href); }
  catch (e) { return { label, total: 0, failures: [{ name: `${label} failed to load`, error: String(e.message ?? e).split('\n')[0] }] }; }
  const failures = [];
  const cases = policyACases(api);
  for (const [name, fn] of cases) {
    try { await fn(); } catch (e) { failures.push({ name, error: String(e.message ?? e).split('\n')[0] }); }
  }
  return { label, total: cases.length, failures };
}

const root = mkdtempSync(path.join(tmpdir(), 'p3c-mutation-'));
let failed = 0;
const rows = [];
try {
  // A disposable mirror so the real .evolve metadata and the real resolver are never touched.
  cpSync('scripts', path.join(root, 'scripts'), { recursive: true });
  const productionBytes = readFileSync(PRIMARY, 'utf8');

  // Baseline: the unmutated resolver must pass every frozen case.
  const baselinePath = path.join(root, 'scripts', 'market-outcomes', 'baseline.mjs');
  writeFileSync(baselinePath, productionBytes);
  const baseline = await runCases('BASELINE', baselinePath);
  if (baseline.failures.length) {
    failed++;
    console.error(`FAIL BASELINE: ${baseline.failures.length} frozen Policy A case(s) fail against the unmutated resolver`);
    for (const f of baseline.failures) console.error(`  FAIL ${f.name}: ${f.error}`);
  } else console.log(`PASS BASELINE ${baseline.total}/${baseline.total} frozen Policy A cases hold against the unmutated resolver`);

  for (const [i, mutation] of MUTATIONS.entries()) {
    let mutated;
    try { mutated = applyMutation(productionBytes, mutation); }
    catch (e) { failed++; console.error(`FAIL ${mutation.id} ${mutation.name}: ${e.message}`); rows.push({ ...mutation, status: 'ANCHOR_ERROR' }); continue; }
    const file = path.join(root, 'scripts', 'market-outcomes', `mutant-${i}.mjs`);
    writeFileSync(file, mutated);
    const result = await runCases(mutation.id, file);
    const survived = result.failures.length === 0;
    const expectedSurvival = Boolean(mutation.equivalent);
    const correct = survived === expectedSurvival;
    if (!correct) failed++;
    const status = survived ? 'SURVIVED' : `KILLED by ${result.failures.length}/${result.total}`;
    rows.push({ ...mutation, status, correct, killedBy: result.failures.map(f => f.name) });
    const tag = mutation.equivalent ? 'CONTROL' : (mutation.critical ? 'CRITICAL' : 'non-critical');
    if (correct) console.log(`PASS ${mutation.id} [${tag}] ${mutation.name} -> ${status}`);
    else console.error(`FAIL ${mutation.id} [${tag}] ${mutation.name} -> ${status} (expected ${expectedSurvival ? 'SURVIVED' : 'KILLED'})`);
    for (const f of result.failures) console.log(`      killed by: ${f.name} :: ${f.error}`);
  }
}
finally { rmSync(root, { recursive: true, force: true }); }

const critical = rows.filter(r => r.critical);
const criticalSurvivors = critical.filter(r => r.status === 'SURVIVED');
const controls = rows.filter(r => r.equivalent);
const controlFailures = controls.filter(r => r.status !== 'SURVIVED');

console.log('');
for (const r of rows) console.log(`${r.id}\t${r.critical ? 'critical' : r.equivalent ? 'control' : 'non-critical'}\t${r.name}\t${r.status}`);
console.log('');
console.log(`P3-C mutation: ${critical.filter(r => r.status.startsWith('KILLED')).length}/${critical.length} critical mutants killed`);
console.log(`P3-C mutation: non-equivalent critical survivors: ${criticalSurvivors.length}`);
console.log(`P3-C mutation: equivalent controls proven surviving: ${controls.length - controlFailures.length}/${controls.length}`);
if (criticalSurvivors.length) { failed++; for (const r of criticalSurvivors) console.error(`SURVIVOR ${r.id}: ${r.name}`); }
if (controlFailures.length) { failed++; console.error('EQUIVALENCE NOT PROVEN: a behaviour-preserving control was killed, so kill results are void'); }
if (failed) process.exitCode = 1;
